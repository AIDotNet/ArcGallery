using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace TKCode.Arc.Gallery.Generators;

/// <summary>
/// Builds <c>GalleryPlaygroundData</c> from the <c>.knobs</c> files: for each one the properties the panel edits (with the
/// editor each needs, the enum members as literals and the property field as a function, so nothing is found by reflection),
/// and the demo's <c>x:Name="Target"</c> element as it is written, from which the panel builds the XAML it shows
/// (design/engineering/gallery-playground.md).
/// </summary>
internal static class PlaygroundEmitter
{
    private const string XamlNamespace = "http://schemas.microsoft.com/winfx/2006/xaml";
    private const string TargetName = "Target";
    private static readonly System.Text.RegularExpressions.Regex s_namespaceDeclaration =
        new(@"\s+xmlns(:\w+)?=""[^""]*""", System.Text.RegularExpressions.RegexOptions.CultureInvariant);

    public static void Emit(SourceProductionContext context, ImmutableArray<KnobFile> files, ImmutableArray<DemoFile> demos,
                            Compilation compilation)
    {
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated />");
        code.AppendLine("// Generated by TKCode.Arc.Gallery.Generators from the gallery's Demos/**/*.knobs files.");
        code.AppendLine("#nullable enable");
        code.AppendLine();
        code.AppendLine("namespace TKCode.Arc.Gallery.Docs;");
        code.AppendLine();
        code.AppendLine("internal static class GalleryPlaygroundData");
        code.AppendLine("{");
        code.AppendLine("    public static readonly GalleryPlayground[] Playgrounds =");
        code.AppendLine("    [");
        foreach (var file in files.OrderBy(f => f.Id, System.StringComparer.Ordinal))
        {
            var entry = Build(context, file, demos, compilation);
            if (entry is not null)
            {
                code.Append(entry);
            }
        }
        code.AppendLine("    ];");
        code.AppendLine("}");
        context.AddSource("GalleryPlaygroundData.g.cs", SourceText.From(code.ToString(), Encoding.UTF8));
    }

    private static string? Build(SourceProductionContext context, KnobFile file, ImmutableArray<DemoFile> demos, Compilation compilation)
    {
        if (file.Problem is not null)
        {
            context.ReportDiagnostic(Diagnostic.Create(GalleryDocsDiagnostics.InvalidKnob, file.Location, file.RelativePath, 0, file.Problem));
            return null;
        }
        var demo = demos.FirstOrDefault(d => d.Id == file.Id && d.Problem is null);
        var target = demo is null ? null : FindTarget(demo.Source);
        if (target is null)
        {
            context.ReportDiagnostic(Diagnostic.Create(GalleryDocsDiagnostics.PlaygroundWithoutTarget, file.Location, file.RelativePath, file.Name + "." + "axaml"));
            return null;
        }
        if (ApiType.Find(compilation, file.Component) is not { } type)
        {
            context.ReportDiagnostic(Diagnostic.Create(GalleryDocsDiagnostics.UnknownKnobProperty, file.Location, file.RelativePath, "(folder)",
                "TKCode.Arc." + file.Component + " (the component folder names no public type)"));
            return null;
        }

        var chain = new List<INamedTypeSymbol>();
        for (var current = type; current is not null && current.SpecialType != SpecialType.System_Object; current = current.BaseType)
        {
            chain.Add(current);
        }

        var knobs = new StringBuilder();
        var count = 0;
        foreach (var line in file.Lines)
        {
            var location = file.Location;
            if (line.Problem is not null)
            {
                context.ReportDiagnostic(Diagnostic.Create(GalleryDocsDiagnostics.InvalidKnob, location, file.RelativePath, line.Line, line.Problem));
                continue;
            }
            var knob = BuildKnob(context, file, line, chain, type);
            if (knob is not null)
            {
                knobs.Append(knob);
                count++;
            }
        }
        if (count == 0)
        {
            return null;
        }

        var entry = new StringBuilder();
        entry.Append("        new(").Append(Literal(file.Id)).Append(", ").Append(Literal(target.Value.Tag)).AppendLine(",");
        entry.Append("            [").Append(string.Join(", ", target.Value.Attributes.Select(a => "new(" + Literal(a.Name) + ", " + Literal(a.Value) + ")"))).AppendLine("],");
        entry.Append("            ").Append(Literal(target.Value.Inner)).AppendLine(",");
        entry.AppendLine("            [");
        entry.Append(knobs);
        entry.AppendLine("            ]),");
        return entry.ToString();
    }

    private static string? BuildKnob(SourceProductionContext context, KnobFile file, KnobLine line, List<INamedTypeSymbol> chain, INamedTypeSymbol type)
    {
        var typeName = type.Name;
        IFieldSymbol? field = null;
        ITypeSymbol? valueType = null;
        var isAttached = false;
        foreach (var owner in chain)
        {
            foreach (var candidate in owner.GetMembers(line.Name + "Property").OfType<IFieldSymbol>())
            {
                if (candidate.IsStatic && candidate.DeclaredAccessibility == Accessibility.Public &&
                    ApiType.PropertyValueType(candidate.Type, out isAttached, out _) is { } found)
                {
                    field = candidate;
                    valueType = found;
                    break;
                }
            }
            if (field is not null)
            {
                break;
            }
        }
        if (field is null || valueType is null)
        {
            context.ReportDiagnostic(Diagnostic.Create(GalleryDocsDiagnostics.UnknownKnobProperty, file.Location, file.RelativePath, line.Name, typeName));
            return null;
        }
        var clr = chain.SelectMany(t => t.GetMembers(line.Name)).OfType<IPropertySymbol>().FirstOrDefault(p => !p.IsStatic);
        if (ApiType.IsHidden(field) || clr is not null && ApiType.IsHidden(clr))
        {
            context.ReportDiagnostic(Diagnostic.Create(GalleryDocsDiagnostics.HiddenKnobProperty, file.Location, file.RelativePath, line.Name));
            return null;
        }
        if (isAttached)
        {
            return Unsupported(context, file, line, "an attached property");
        }
        if (clr is not null && clr.SetMethod is not { DeclaredAccessibility: Accessibility.Public })
        {
            return Unsupported(context, file, line, "it is read-only");
        }

        var nullable = false;
        if (valueType is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } wrapper)
        {
            nullable = true;
            valueType = wrapper.TypeArguments[0];
        }

        string kind;
        var extra = new StringBuilder();
        switch (valueType.SpecialType)
        {
            case SpecialType.System_Boolean:
                kind = "Switch";
                break;
            case SpecialType.System_String:
            case SpecialType.System_Object:
                // An object property such as Content takes the text the panel gives it.
                kind = "Text";
                if (line.Presets.Count > 0)
                {
                    extra.Append(", Presets = [").Append(string.Join(", ", line.Presets.Select(Literal))).Append("]");
                }
                break;
            case SpecialType.System_Int32:
            case SpecialType.System_Double:
                kind = "Number";
                if (line.Min is not { } min || line.Max is not { } max || min >= max)
                {
                    context.ReportDiagnostic(Diagnostic.Create(GalleryDocsDiagnostics.InvalidKnob, file.Location, file.RelativePath, line.Line,
                        "'" + line.Name + "' is a number and needs a range, such as '" + line.Name + " 0..100'"));
                    return null;
                }
                var integer = valueType.SpecialType == SpecialType.System_Int32;
                var step = line.Step ?? (integer ? 1 : (max - min) / 100);
                extra.Append(", Min = ").Append(Double(min)).Append(", Max = ").Append(Double(max)).Append(", Step = ").Append(Double(step));
                if (integer)
                {
                    extra.Append(", IsInteger = true");
                }
                break;
            default:
                if (valueType.TypeKind == TypeKind.Enum)
                {
                    var members = valueType.GetMembers().OfType<IFieldSymbol>()
                        .Where(f => f.HasConstantValue && f.DeclaredAccessibility == Accessibility.Public && !ApiType.IsHidden(f)).ToList();
                    if (valueType.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "System.FlagsAttribute"))
                    {
                        return Unsupported(context, file, line, "a [Flags] enum");
                    }
                    foreach (var name in line.Only)
                    {
                        if (members.All(m => m.Name != name))
                        {
                            context.ReportDiagnostic(Diagnostic.Create(GalleryDocsDiagnostics.InvalidKnob, file.Location, file.RelativePath, line.Line,
                                "'" + name + "' is not a member of " + valueType.Name));
                            return null;
                        }
                    }
                    if (line.Only.Count > 0)
                    {
                        members = line.Only.Select(name => members.First(m => m.Name == name)).ToList();
                    }
                    var typeExpression = valueType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                    kind = "Choice";
                    extra.Append(", Choices = [").Append(string.Join(", ", members.Select(m =>
                        "new(" + Literal(m.Name) + ", (object)" + typeExpression + "." + m.Name + ")"))).Append("]");
                    break;
                }
                return Unsupported(context, file, line, "its type is " + valueType.ToDisplayString());
        }

        var fieldExpression = field.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "." + field.Name;
        var result = new StringBuilder();
        result.Append("                new(").Append(Literal(line.Name)).Append(", GalleryKnobKind.").Append(kind)
              .Append(", static () => ").Append(fieldExpression).Append(", ").Append(nullable ? "true" : "false").Append(", ")
              .Append(Literal(line.Group)).Append(", ").Append(Literal(ApiOwner(field.ContainingType, chain))).Append(")");
        if (extra.Length > 0)
        {
            result.Append(" { ").Append(extra.ToString().TrimStart(',', ' ')).Append(" }");
        }
        result.AppendLine(",");
        return result.ToString();
    }

    /// <summary>The name the API translations key the property by: its declaring Arc type, or null for an Avalonia base type.</summary>
    private static string? ApiOwner(INamedTypeSymbol owner, List<INamedTypeSymbol> chain)
        => ApiType.IsArc(owner) ? ApiType.ApiName(owner) : null;

    private static string? Unsupported(SourceProductionContext context, KnobFile file, KnobLine line, string reason)
    {
        context.ReportDiagnostic(Diagnostic.Create(GalleryDocsDiagnostics.UnsupportedKnobType, file.Location, file.RelativePath, line.Name, reason));
        return null;
    }

    /// <summary>The element named <c>Target</c> in the demo's XAML: its tag as written and its attributes (without the name).</summary>
    private static (string Tag, List<(string Name, string Value)> Attributes, string? Inner)? FindTarget(string source)
    {
        XDocument document;
        try
        {
            document = XDocument.Parse(source);
        }
        catch (XmlException)
        {
            return null;
        }
        var element = document.Descendants().FirstOrDefault(e => (string?)e.Attribute(XName.Get("Name", XamlNamespace)) == TargetName);
        if (element is null)
        {
            return null;
        }
        var attributes = new List<(string, string)>();
        foreach (var attribute in element.Attributes())
        {
            if (attribute.IsNamespaceDeclaration || attribute.Name == XName.Get("Name", XamlNamespace))
            {
                continue;
            }
            attributes.Add((QualifiedName(attribute.Name, element), attribute.Value));
        }
        // The children as the demo writes them, re-indented by the XML writer, without the namespace declarations it adds
        // to each (they are declared on the demo's root).
        string? inner = null;
        if (element.HasElements)
        {
            inner = string.Join("\n", element.Elements().Select(child => s_namespaceDeclaration.Replace(child.ToString(), string.Empty)));
        }
        return (QualifiedName(element.Name, element), attributes, inner);
    }

    private static string QualifiedName(XName name, XElement scope)
    {
        if (name.Namespace == XNamespace.None)
        {
            return name.LocalName;
        }
        var prefix = scope.GetPrefixOfNamespace(name.Namespace);
        return string.IsNullOrEmpty(prefix) ? name.LocalName : prefix + ":" + name.LocalName;
    }

    private static string Double(double value) => value.ToString("R", CultureInfo.InvariantCulture) + "d";

    private static string Literal(string? value) => value is null ? "null" : SymbolDisplay.FormatLiteral(value, quote: true);
}
